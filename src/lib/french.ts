/** Translate known application labels without rewriting user-supplied observations. */
export function fr(value: string): string {
  return labels[value] ?? value;
}

export function frenchError(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error ?? "");
  if (labels[message]) return fr(message);
  if (/invalid login credentials/i.test(message)) return "Adresse e-mail ou mot de passe incorrect.";
  if (/email not confirmed/i.test(message)) return "Confirmez votre adresse e-mail avant de vous connecter.";
  if (/already registered/i.test(message)) return "Cette adresse e-mail est déjà enregistrée.";
  if (/rate limit|too many requests/i.test(message)) return "Trop de demandes. Veuillez patienter avant de réessayer.";
  if (/fetch|network/i.test(message)) return "Connexion indisponible. Vérifiez votre connexion et réessayez.";
  if (/session|unauthorized|jwt|authentication/i.test(message)) return "Votre session a expiré. Veuillez vous reconnecter.";
  if (/revision|conflict|changed/i.test(message)) return "Les données ont changé. Rechargez la page avant de réessayer.";
  if (/[àâéèêëîïôùûüçœ]/i.test(message)) return message;
  return "La demande n’a pas pu aboutir. Veuillez réessayer.";
}

export function formatDate(value: string): string {
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? value : new Intl.DateTimeFormat("fr-FR", {dateStyle: "short", timeStyle: "short"}).format(date);
}
